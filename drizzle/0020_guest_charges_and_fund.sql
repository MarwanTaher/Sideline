-- Session charges for non-core players, and the group fund they feed.
--
-- Core subscribers pay a fixed monthly amount (unchanged). Everyone else pays
-- a flat per-session rate. Who receives it depends on why they are playing:
--   - covering for an absent subscriber  -> they pay that subscriber (rules §8,
--     settled between the two, never group money)
--   - playing beyond the core 14         -> they pay the group fund
--
-- The fund's balance is derived from these rows rather than stored, so it can
-- never drift out of step with what was actually charged.
--
-- Idempotent: safe to re-run.

ALTER TABLE seasons ADD COLUMN IF NOT EXISTS guest_rate_minor integer DEFAULT 3600 NOT NULL;

