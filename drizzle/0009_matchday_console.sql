-- Matchday live console: rotating short-side rounds with a live goal/assist log
-- and a per-round stopwatch. All statements are idempotent (safe to re-run).

-- One row per short game played during a matchday (e.g. rotating 15-min games).
CREATE TABLE IF NOT EXISTS match_rounds (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
        round_no integer NOT NULL,
        team_a integer NOT NULL,
        team_b integer NOT NULL,
        status text NOT NULL DEFAULT 'active',
        -- Stopwatch state. Time is tracked in epoch milliseconds so the client
        -- and server agree without timezone math: elapsed_ms is the accumulated
        -- time while paused; when running, add (now - started_at_ms).
        timer_running integer NOT NULL DEFAULT 0,
        elapsed_ms bigint NOT NULL DEFAULT 0,
        started_at_ms bigint,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT match_rounds_status_check CHECK (status IN ('active', 'done')),
        CONSTRAINT match_rounds_timer_check CHECK (timer_running IN (0, 1)),
        CONSTRAINT match_rounds_match_round_unique UNIQUE (match_id, round_no)
);
CREATE INDEX IF NOT EXISTS idx_match_rounds_match ON match_rounds (match_id);

-- One row per goal scored in a round. The scorer/assist may be a roster player
-- or a drafted guest; exactly one of the *_player_id / *_guest_id pair is set.
CREATE TABLE IF NOT EXISTS round_goals (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        round_id integer NOT NULL REFERENCES match_rounds(id) ON DELETE CASCADE,
        match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
        team_no integer NOT NULL,
        scorer_player_id integer REFERENCES players(id) ON DELETE SET NULL,
        scorer_guest_id integer REFERENCES match_guests(id) ON DELETE SET NULL,
        assist_player_id integer REFERENCES players(id) ON DELETE SET NULL,
        assist_guest_id integer REFERENCES match_guests(id) ON DELETE SET NULL,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_round_goals_round ON round_goals (round_id);
CREATE INDEX IF NOT EXISTS idx_round_goals_match ON round_goals (match_id);
