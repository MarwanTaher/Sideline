-- Season replacements board (roadmap F-4).
--
-- A core subscriber who will miss a season match offers their seat; players on
-- that match's waitlist request it and the subscriber approves one of them.
-- The approved replacement takes the seat and pays the subscriber directly
-- (rules §8, a guest_charges row with kind = 'replacement').
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS seat_offers (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    subscriber_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    status text DEFAULT 'open' NOT NULL,
    replacement_player_id integer REFERENCES players(id) ON DELETE SET NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    filled_at timestamptz,
    CONSTRAINT seat_offers_status_check CHECK (status IN ('open', 'filled', 'withdrawn')),
    -- filled_at is set exactly when the offer is filled.
    CONSTRAINT seat_offers_filled_check CHECK ((status = 'filled') = (filled_at IS NOT NULL)),
    CONSTRAINT seat_offers_not_self_check
        CHECK (replacement_player_id IS NULL OR replacement_player_id <> subscriber_id)
);

