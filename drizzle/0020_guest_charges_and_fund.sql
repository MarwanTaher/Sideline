-- Cost of extending the session (100 PLN for the extra half hour).
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS extension_cost_minor integer DEFAULT 10000 NOT NULL;

--> statement-breakpoint

-- Extra players needed before extending pays for itself.
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS extension_min_extra integer DEFAULT 4 NOT NULL;

--> statement-breakpoint

ALTER TABLE matches ADD COLUMN IF NOT EXISTS extended boolean DEFAULT false NOT NULL;

--> statement-breakpoint

CREATE TABLE IF NOT EXISTS guest_charges (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    -- A registered player who is not a core subscriber...
    player_id integer REFERENCES players(id) ON DELETE CASCADE,
    -- ...or an invited guest who has no account.
    guest_id integer REFERENCES match_guests(id) ON DELETE CASCADE,
    amount_minor integer NOT NULL,
    kind text DEFAULT 'extra' NOT NULL,
    -- Set only for 'replacement': the subscriber who is owed the money.
    owed_to_player_id integer REFERENCES players(id) ON DELETE SET NULL,
    paid_at timestamptz,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT guest_charges_kind_check CHECK (kind IN ('extra', 'replacement')),
    CONSTRAINT guest_charges_who_check
        CHECK ((player_id IS NOT NULL) <> (guest_id IS NOT NULL)),
    -- A replacement must say who it reimburses; an extra must not.
    CONSTRAINT guest_charges_owed_check
        CHECK ((kind = 'replacement') = (owed_to_player_id IS NOT NULL))
);

--> statement-breakpoint

CREATE UNIQUE INDEX IF NOT EXISTS guest_charges_player_idx
    ON guest_charges (match_id, player_id) WHERE player_id IS NOT NULL;

--> statement-breakpoint

CREATE UNIQUE INDEX IF NOT EXISTS guest_charges_guest_idx
    ON guest_charges (match_id, guest_id) WHERE guest_id IS NOT NULL;

--> statement-breakpoint

-- Anything the fund receives or spends that isn't a guest fee or an extension.
CREATE TABLE IF NOT EXISTS fund_adjustments (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    season_id integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
    amount_minor integer NOT NULL,
    note text DEFAULT '' NOT NULL,
    created_by text DEFAULT '' NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL
);
