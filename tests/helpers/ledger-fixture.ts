import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";

// In-memory fixtures only: never loads DATABASE_URL or contacts Neon.

/** The payment tables as they are after 0038 (the columns 0039 reads). */
export const LEDGER_SCHEMA = `
  CREATE TABLE players(id integer PRIMARY KEY, name text);
  CREATE TABLE seasons(id integer PRIMARY KEY, subscription_enabled boolean, new_rules_from text,
    extension_cost_minor integer DEFAULT 10000);
  CREATE TABLE matches(id integer PRIMARY KEY, played_on text, season_id integer REFERENCES seasons(id),
    payments_active integer DEFAULT 0, total_payment double precision DEFAULT 0, payment_currency text DEFAULT 'PLN',
    share_minor integer, extended boolean DEFAULT false, extension_cost_minor integer);
  CREATE TABLE match_players(match_id integer REFERENCES matches(id) ON DELETE CASCADE, player_id integer);
  CREATE TABLE payments(match_id integer REFERENCES matches(id) ON DELETE CASCADE, player_id integer,
    paid integer DEFAULT 0, updated_at timestamp DEFAULT now(), PRIMARY KEY(match_id, player_id));
  CREATE TABLE match_guests(id integer PRIMARY KEY, match_id integer REFERENCES matches(id) ON DELETE CASCADE,
    name text, host_player_id integer, paid integer DEFAULT 0, status text DEFAULT 'approved');
  CREATE TABLE season_invoices(id integer PRIMARY KEY, season_id integer, player_id integer, period text,
    gross_minor integer, credit_minor integer DEFAULT 0, due_date text, paid_at timestamptz,
    declared_paid_at timestamptz, declared_note text DEFAULT '', hidden_at timestamptz);
  CREATE TABLE guest_charges(id integer PRIMARY KEY, match_id integer REFERENCES matches(id) ON DELETE CASCADE,
    player_id integer, guest_id integer, amount_minor integer, kind text, owed_to_player_id integer,
    paid_at timestamptz, scan_credit_minor integer DEFAULT 0, scan_refunded_at timestamptz);
  CREATE TABLE matchday_settlements(match_id integer PRIMARY KEY REFERENCES matches(id) ON DELETE CASCADE,
    expected_minor integer, paid_minor integer, recorded_at timestamptz DEFAULT now());
  CREATE TABLE fund_adjustments(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, season_id integer,
    amount_minor integer, note text DEFAULT '', created_at timestamptz DEFAULT now());

`;

/** Apply drizzle/0039_payments_ledger.sql (views, ledger tables, triggers). */
export async function applyLedgerMigration(db: PGlite): Promise<void> {
  const sql = readFileSync(new URL("../../drizzle/0039_payments_ledger.sql", import.meta.url), "utf8");
  for (const statement of sql.split("--> statement-breakpoint")) {
    if (statement.trim()) await db.query(statement);
  }
}

/** A fresh database with the payment tables, 0039 applied, and `seed` run after. */
export async function ledgerDb(seed = ""): Promise<PGlite> {
  const db = new PGlite();
  await db.exec(LEDGER_SCHEMA);
  await applyLedgerMigration(db);
  if (seed) await db.exec(seed);
  return db;
}
