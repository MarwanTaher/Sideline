-- One live (open or filled) offer per subscriber per match; withdrawn offers
-- are history and do not block a new one.
CREATE UNIQUE INDEX IF NOT EXISTS seat_offers_live_idx
    ON seat_offers (match_id, subscriber_id) WHERE status IN ('open', 'filled');

