CREATE FUNCTION sideline_promote_waitlist(p_match integer, p_player integer) RETURNS boolean
LANGUAGE plpgsql AS $$
DECLARE m matches%ROWTYPE; first_id integer;
BEGIN
  SELECT * INTO m FROM matches WHERE id=p_match FOR UPDATE;
  IF NOT FOUND OR NOT sideline_public_signup_open(p_match) OR m.matchday_status='closed'
     OR now() >= m.kickoff_at - interval '24 hours' THEN RETURN false; END IF;
  DELETE FROM match_waitlist w WHERE w.match_id=p_match AND (
    NOT EXISTS(SELECT 1 FROM players p WHERE p.id=w.player_id AND p.active=1 AND p.deleted_at IS NULL)
    OR EXISTS(SELECT 1 FROM match_availability a WHERE a.match_id=p_match AND a.player_id=w.player_id AND a.status='in'));
  SELECT w.player_id INTO first_id FROM match_waitlist w
    JOIN players p ON p.id=w.player_id AND p.active=1 AND p.deleted_at IS NULL
    WHERE w.match_id=p_match ORDER BY w.position,w.player_id LIMIT 1;
  IF first_id IS DISTINCT FROM p_player OR sideline_squad_count(p_match) >= COALESCE(m.max_players,18) THEN RETURN false; END IF;
  DELETE FROM match_waitlist WHERE match_id=p_match AND player_id=p_player;
  IF EXISTS(SELECT 1 FROM match_availability WHERE match_id=p_match AND player_id=p_player AND status='in') THEN RETURN false; END IF;
  INSERT INTO match_availability(match_id,player_id,status,updated_at) VALUES(p_match,p_player,'in',now())
  ON CONFLICT(match_id,player_id) DO UPDATE SET status='in',updated_at=now();
  RETURN true;
END
$$;

