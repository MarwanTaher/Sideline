import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { createSourceFile, ScriptTarget, isNoSubstitutionTemplateLiteral, forEachChild, type Node } from "typescript";

// In-memory fixtures only: this suite never loads DATABASE_URL or contacts Neon.
test("automation migration and transactional invariants in isolated PostgreSQL", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE TABLE seasons(id integer PRIMARY KEY, start_date text, end_date text, status text, subscription_enabled boolean,
        subscriber_cap integer, visible_to_players boolean, rates_confirmed_at timestamptz, terms_final_at timestamptz,
        test_invoice_completed_at timestamptz, reminder_text_reviewed_at timestamptz, payment_name text, payment_account text,
        terms text, day_rate_minor integer);
      CREATE TABLE players(id integer PRIMARY KEY, active integer DEFAULT 1, deleted_at timestamptz);
      CREATE TABLE matches(id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, played_on text, match_time text,
        kickoff_at timestamptz, num_teams integer, team_size integer, total_payment double precision,
        stats_scoring_enabled integer, status text, matchday_status text DEFAULT 'draft', season_id integer,
        location_name text, location_lat double precision,location_lng double precision,venue text, payment_currency text, max_players integer DEFAULT 18,
        availability_open integer DEFAULT 1, extended boolean DEFAULT false);
      CREATE TABLE match_availability(match_id integer REFERENCES matches(id) ON DELETE CASCADE, player_id integer REFERENCES players(id),
        status text CHECK(status IN ('in','out')), updated_at timestamptz, PRIMARY KEY(match_id,player_id));
      CREATE TABLE match_guests(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,match_id integer REFERENCES matches(id) ON DELETE CASCADE,
        host_player_id integer, status text);
      CREATE TABLE season_subscriptions(season_id integer,player_id integer,status text,accepted_at timestamptz DEFAULT now());
      CREATE TABLE app_settings(key text PRIMARY KEY,value text);
      INSERT INTO seasons VALUES(1,to_char((now()+interval '2 days') AT TIME ZONE 'Europe/Warsaw','YYYY-MM-DD'),
        to_char((now()+interval '30 days') AT TIME ZONE 'Europe/Warsaw','YYYY-MM-DD'),'active',true,
        14,true,now(),now(),now(),now(),'Fictional club','fictional account','Fictional terms',50000);
      INSERT INTO players(id) SELECT generate_series(1,30);
      INSERT INTO season_subscriptions(season_id,player_id,status) SELECT 1,generate_series(1,14),'active';
      INSERT INTO app_settings VALUES('availability_lock_24h','1');
      INSERT INTO matches(played_on,kickoff_at) VALUES('2000-01-02','2000-01-02T20:00Z');
      INSERT INTO app_settings VALUES('waitlist_1','18, 17,18,invalid');
    `);
    const statements = readFileSync(new URL("../drizzle/0037_match_automation.sql", import.meta.url), "utf8").split("--> statement-breakpoint");
    for (const statement of statements) await db.query(statement);
    const scalar = async <T>(sql: string, params: unknown[] = []) => (await db.query<{ value: T }>(sql, params)).rows[0].value;
    assert.deepEqual((await db.query<{ player_id: number }>(`SELECT player_id FROM match_waitlist WHERE match_id=1 ORDER BY position`)).rows.map((r) => r.player_id), [18, 17]);
    const source = createSourceFile("match-automation.ts",readFileSync(new URL("../src/lib/match-automation.ts",import.meta.url),"utf8"),ScriptTarget.Latest);
    let saveSql = "";
    const findSaveSql = (node: Node) => {
      if (isNoSubstitutionTemplateLiteral(node) && node.text.startsWith("INSERT INTO season_match_automation(")) saveSql=node.text;
      forEachChild(node,findSaveSql);
    };
    findSaveSql(source);
    assert.ok(saveSql,"execute the actual application's parameterized save SQL without loading database configuration");
    const scheduleFor = async (weekday: number) => (await db.query<{ date: string }>(`
      SELECT to_char(day,'YYYY-MM-DD') AS date FROM seasons,
        generate_series(start_date::date::timestamp,end_date::date::timestamp,interval '1 day') day
      WHERE id=1 AND extract(dow FROM day)=$1 ORDER BY day`,[weekday])).rows.map((r)=>r.date);
    const saveParams = [1,0,"21:00",5,"15:00",90,30,18,18,3,true,"Fictional pitch","indoor",true,false,null,null,JSON.stringify(await scheduleFor(0))];
    await db.query(saveSql,saveParams);
    await db.exec("UPDATE seasons SET rates_confirmed_at=NULL");
    await assert.rejects(db.query("SELECT sideline_generate_match(1)"), /go-live checklist/);
    assert.equal(await scalar<number>("SELECT COUNT(*)::int AS value FROM season_match_occurrences"), 0);
    await db.exec("UPDATE seasons SET rates_confirmed_at=now()");
    const matchId = await scalar<number>("SELECT sideline_generate_match(1) AS value");
    assert.ok(matchId > 1);
    assert.equal(await scalar<number>("SELECT sideline_squad_count($1) AS value", [matchId]), 14);
    assert.equal(await scalar<number | null>("SELECT sideline_generate_match(1) AS value"), null);
    await db.query(`UPDATE matches SET kickoff_at=now()+interval '7 days',signup_opens_at=now()+interval '2 days' WHERE id=$1`, [matchId]);
    assert.equal(await scalar<boolean>("SELECT sideline_public_signup_open($1) AS value", [matchId]), false);
    assert.equal(await scalar<string>("SELECT sideline_respond($1,1,'out',true) AS value", [matchId]), "out");
    await assert.rejects(db.query("SELECT sideline_respond($1,15,'in',true)", [matchId]), /not open/);
    assert.equal(await scalar<number>("SELECT sideline_seed_subscribers($1) AS value", [matchId]), 0, "explicit OUT is preserved");
    await assert.rejects(db.query("SELECT sideline_assert_response($1,1,true)", [matchId]), /not open/, "core cannot bypass public guest/seat gate");
    await db.query(`UPDATE matches SET signup_opens_at=now() WHERE id=$1`, [matchId]);
    assert.equal(await scalar<boolean>("SELECT sideline_public_signup_open($1) AS value", [matchId]), true);
    for (let id = 15; id <= 19; id++) assert.equal(await scalar<string>("SELECT sideline_respond($1,$2,'in',true) AS value", [matchId, id]), "in");
    assert.equal(await scalar<number>("SELECT sideline_squad_count($1) AS value", [matchId]), 18);
    assert.equal(await scalar<string>("SELECT sideline_respond($1,20,'in',true) AS value", [matchId]), "waitlist:1");
    assert.equal(await scalar<string>("SELECT sideline_respond($1,21,'in',true) AS value", [matchId]), "waitlist:2");
    assert.equal(await scalar<string>("SELECT sideline_respond($1,20,'in',true) AS value", [matchId]), "waitlist:1");
    await assert.rejects(db.query("INSERT INTO match_guests(match_id,host_player_id,status) VALUES($1,2,'approved')", [matchId]), /full/);
    await assert.rejects(db.query("UPDATE matches SET max_players=17 WHERE id=$1", [matchId]), /below/);
    await db.query("SELECT sideline_confirm_extension($1,true)", [matchId]);
    assert.equal(await scalar<boolean>("SELECT extended AS value FROM matches WHERE id=$1", [matchId]), true);
    await db.query("SELECT sideline_confirm_extension($1,false)", [matchId]);
    await db.query("SELECT sideline_respond($1,15,'out',true)", [matchId]);
    await assert.rejects(db.query("SELECT sideline_confirm_extension($1,true)", [matchId]), /18 participants/);
    assert.equal(await scalar<boolean>("SELECT sideline_promote_waitlist($1,21) AS value", [matchId]), false, "queue cannot jump");
    assert.equal(await scalar<boolean>("SELECT sideline_promote_waitlist($1,20) AS value", [matchId]), true);
    assert.equal(await scalar<boolean>("SELECT sideline_promote_waitlist($1,20) AS value", [matchId]), false);
    await db.query("SELECT sideline_waitlist_edit($1,22,'join')", [matchId]);
    await db.exec("UPDATE players SET active=0 WHERE id=21");
    await db.query("SELECT sideline_respond($1,16,'out',true)", [matchId]);
    assert.equal(await scalar<boolean>("SELECT sideline_promote_waitlist($1,22) AS value", [matchId]), true, "inactive head does not stall promotion");
    assert.equal(await scalar<number>("SELECT COUNT(*)::int AS value FROM match_waitlist WHERE match_id=$1 AND player_id=21", [matchId]),0);
    await db.query("UPDATE matches SET extension_minutes=0 WHERE id=$1", [matchId]);
    await assert.rejects(db.query("SELECT sideline_confirm_extension($1,true)", [matchId]), /no optional extension/);
    await db.query("UPDATE matches SET extension_minutes=30 WHERE id=$1", [matchId]);
    await db.query("UPDATE matches SET availability_override='closed' WHERE id=$1", [matchId]);
    assert.equal(await scalar<boolean>("SELECT sideline_public_signup_open($1) AS value", [matchId]), false);
    await assert.rejects(db.query("UPDATE matches SET kickoff_at=now()+interval '24 hours' WHERE id=$1", [matchId]), /Rescheduling cannot/);
    // Move the fixture clock to the lock boundary without using the admin rescheduling path.
    await db.exec("ALTER TABLE matches DISABLE TRIGGER automation_match_edit");
    await db.query("UPDATE matches SET availability_override=NULL,kickoff_at=now()+interval '24 hours' WHERE id=$1", [matchId]);
    await db.exec("ALTER TABLE matches ENABLE TRIGGER automation_match_edit");
    await assert.rejects(db.query("SELECT sideline_respond($1,2,'out',true)", [matchId]), /locked/);
    assert.equal(await scalar<boolean>("SELECT sideline_promote_waitlist($1,21) AS value", [matchId]), false);
    await db.query("UPDATE matches SET matchday_status='closed' WHERE id=$1", [matchId]);
    await assert.rejects(db.query("UPDATE matches SET kickoff_at=now()+interval '14 days' WHERE id=$1", [matchId]), /unlocked draft booking/);
    assert.equal(await scalar<boolean>("SELECT needs_generation AS value FROM season_match_automation WHERE season_id=1"), true);
    await db.exec("UPDATE season_match_automation SET paused=true");
    assert.equal(await scalar<number | null>("SELECT sideline_generate_match(1) AS value"), null);
    await db.exec("UPDATE season_match_automation SET paused=false");
    const originalDate = await scalar<string>("SELECT played_on AS value FROM matches WHERE id=$1",[matchId]);
    saveParams[1]=1;
    saveParams[17]=JSON.stringify(await scheduleFor(1));
    await db.query(saveSql,saveParams);
    assert.equal(await scalar<boolean>("SELECT scheduled_dates ? $1 AS value FROM season_match_automation WHERE season_id=1",[originalDate]),true,"template edits retain the existing booking calendar");
    const nextId = await scalar<number>("SELECT sideline_generate_match(1) AS value");
    assert.ok(nextId > matchId);
    await db.query("UPDATE matches SET kickoff_at=kickoff_at+interval '1 hour' WHERE id=$1", [nextId]);
    assert.equal(await scalar<boolean>("SELECT m.kickoff_at=o.kickoff_at AND m.signup_opens_at=o.opens_at AS value FROM matches m JOIN season_match_occurrences o ON o.match_id=m.id WHERE m.id=$1",[nextId]),true);
    await db.query("UPDATE matches SET matchday_status='draft' WHERE id=$1", [matchId]);
    await db.query("UPDATE matches SET matchday_status='closed' WHERE id=$1", [matchId]);
    assert.equal(await scalar<boolean>("SELECT needs_generation AS value FROM season_match_automation WHERE season_id=1"), false, "old reclosure does not create another successor");
    await db.exec("UPDATE seasons SET status='archived'");
    assert.equal(await scalar<boolean>("SELECT sideline_public_signup_open($1) AS value", [nextId]), false);
    await db.exec("UPDATE seasons SET status='active'");
    await db.query("UPDATE matches SET matchday_status='closed' WHERE id=$1", [nextId]);
    await db.exec("UPDATE seasons SET end_date=to_char(now(),'YYYY-MM-DD')");
    assert.equal(await scalar<number | null>("SELECT sideline_generate_match(1) AS value"), null, "no match beyond season end");
    await db.exec(`
      INSERT INTO seasons SELECT (jsonb_populate_record(NULL::seasons,to_jsonb(s)||jsonb_build_object(
        'id',2,'start_date',to_char((now()+interval '30 minutes') AT TIME ZONE 'Europe/Warsaw','YYYY-MM-DD'),
        'end_date',to_char((now()+interval '30 minutes') AT TIME ZONE 'Europe/Warsaw','YYYY-MM-DD')))).*
        FROM seasons s WHERE id=1;
      INSERT INTO season_subscriptions(season_id,player_id,status) SELECT 2,generate_series(1,14),'active';
      INSERT INTO season_match_automation(season_id,enabled,needs_generation,weekday,kickoff_time,opening_weekday)
        SELECT 2,true,true,extract(dow FROM (now()+interval '30 minutes') AT TIME ZONE 'Europe/Warsaw')::int,
          to_char((now()+interval '30 minutes') AT TIME ZONE 'Europe/Warsaw','HH24:MI'),
          (extract(dow FROM (now()+interval '30 minutes') AT TIME ZONE 'Europe/Warsaw')::int+5)%7;
    `);
    const lateId=await scalar<number>("SELECT sideline_generate_match(2) AS value");
    assert.ok(lateId>nextId);
    assert.match(await scalar<string>("SELECT last_error AS value FROM season_match_automation WHERE season_id=2"),/inside the 24-hour lock/);
    await assert.rejects(db.query("SELECT sideline_respond($1,1,'out',true)",[lateId]),/locked/);
  } finally { await db.close(); }
});
