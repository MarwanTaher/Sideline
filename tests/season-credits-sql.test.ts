test("invoice credit: scans first, then replacement credits into what is left", async () => {
  const db = await fixture();
  try {
    await db.exec(`
      -- 143 PLN bill; 10 scans x 15 = 150 would overflow, so only 9 fit (135).
      INSERT INTO season_invoices(id, season_id, player_id, period, gross_minor, due_date)
        VALUES (100, 1, 1, '2027-01', 14286, '2027-01-03');
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor)
        SELECT g, 11, 1, 'approved', 1500 FROM generate_series(1, 2) g;
      INSERT INTO season_credits(season_id, player_id, source, guest_charge_id, credit_minor)
        VALUES (1, 1, 'replacement', 2, 3600), (1, 1, 'replacement', NULL, 3600),
               (1, 1, 'replacement', NULL, 9000);
    `);
    const run = async () => {
      for (const statement of REALLOCATE_CREDIT_SQL) await db.query(statement, [100]);
    };
    await run();
    const credit = async () =>
      (await db.query<{ credit_minor: number }>(`SELECT credit_minor FROM season_invoices WHERE id = 100`)).rows[0].credit_minor;
    // 2 scans (30) + 36 + 36 = 102; the 90 credit doesn't fit 143 any more.
    assert.equal(await credit(), 10200);
    const applied = (await db.query<{ id: number }>(
      `SELECT id FROM season_credits WHERE applied_invoice_id = 100 ORDER BY id`)).rows.map((r) => Number(r.id));
    assert.deepEqual(applied, [1, 2]);

    // Re-running is stable.
    await run();
    assert.equal(await credit(), 10200);

    // A smaller bill drops the replacement credits before the scans.
    await db.exec(`UPDATE season_invoices SET gross_minor = 5000 WHERE id = 100`);
    await run();
    assert.equal(await credit(), 3000);

    // Paid bills are never refitted.
    await db.exec(`UPDATE season_invoices SET gross_minor = 14286, paid_at = now() WHERE id = 100`);
    await run();
    assert.equal(await credit(), 3000);
  } finally {
    await db.close();
  }
});

test("leftover credit: scans and replacement credits listed and settled together", async () => {
  const db = await fixture();
  try {
    await db.exec(`
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor) VALUES (1, 11, 1, 'approved', 1500);
      INSERT INTO season_credits(season_id, player_id, source, guest_charge_id, credit_minor)
        VALUES (1, 1, 'replacement', 2, 3600);
    `);
    const left = (await db.query<{ credit: number; scans: number; replacements: number }>(
      LEFTOVER_CREDITS_SQL, [1])).rows;
    assert.deepEqual(left.map((r) => [r.credit, r.scans, r.replacements]), [[5100, 1, 1]]);

    const settled = (await db.query<{ amount: number }>(SETTLE_LEFTOVER_CREDIT_SQL, [1, 1, "fund", "end", "admin"])).rows;
    assert.equal(settled[0].amount, 5100);
    const fund = (await db.query<{ amount_minor: number }>(`SELECT amount_minor FROM fund_adjustments`)).rows;
    assert.deepEqual(fund, [{ amount_minor: 5100 }]);
    assert.equal((await db.query(LEFTOVER_CREDITS_SQL, [1])).rows.length, 0);
  } finally {
    await db.close();
  }
});

test("scan on the fee: new-rules non-core scans reduce that fee once; old rules wait", async () => {
  const { APPLY_SCANS_TO_CHARGES_SQL } = await import("../src/lib/season-fund-sql");
  const db = await fixture();
  try {
    await db.exec(`
      -- Cara: extra on 11 (new rules, paid) and 10 (old rules).
      INSERT INTO guest_charges(id, match_id, player_id, amount_minor, kind, paid_at) VALUES
        (5, 10, 3, 3600, 'extra', NULL);
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor) VALUES
        (1, 11, 3, 'approved', 1500),
        (2, 10, 3, 'approved', 1500),
        (3, 12, 2, 'pending', 1500),
        (4, 11, 1, 'approved', 1500);   -- core subscriber: no charge, stays for the invoice
    `);
    const run = async (m: number) => (await db.query(APPLY_SCANS_TO_CHARGES_SQL, [m])).rows.length;
    assert.equal(await run(11), 1);
    assert.equal(await run(11), 0); // idempotent
    assert.equal(await run(10), 0); // before the cutover
    assert.equal(await run(12), 0); // not approved

    const scans = (await db.query<{ id: number; settled_as: string | null }>(
      `SELECT id, settled_as FROM multisport_scans ORDER BY id`)).rows;
    assert.deepEqual(scans.map((r) => [r.id, r.settled_as]), [[1, "fee"], [2, null], [3, null], [4, null]]);
    const credit = (await db.query<{ scan_credit_minor: number }>(
      `SELECT scan_credit_minor FROM guest_charges WHERE id = 4`)).rows[0];
    assert.equal(credit.scan_credit_minor, 1500);

    // Charge 4 was paid in full before the scan: the ledger keeps the 36 paid
    // (the 15 goes back as a refund). An unpaid fee shows the reduced amount.
    let dues = (await db.query<DueRow>(PLAYER_DUES_SQL, [3])).rows.map(toDue);
    assert.deepEqual(dues.map((d) => [d.key, d.amountMinor]), [["charge:4", 3600], ["charge:5", 3600]]);
    await db.exec(`UPDATE guest_charges SET paid_at = NULL WHERE id = 4`);
    dues = (await db.query<DueRow>(PLAYER_DUES_SQL, [3])).rows.map(toDue);
    assert.equal(dues.find((d) => d.key === "charge:4")?.amountMinor, 2100);
  } finally {
    await db.close();
  }
});

test("charge scan fields: payable amount and refund after an early payment", async () => {
  const { chargeScanFields } = await import("../src/lib/charge-scan");
  const base = { amountMinor: 3600, scanCreditMinor: 1500, scanRefundedAt: null };
  assert.deepEqual(chargeScanFields({ ...base, paidAt: null, scanSettledAt: "2026-12-07T10:00:00Z" }),
    { scanCreditMinor: 1500, payableMinor: 2100, refundDueMinor: 0 });
  // Paid 36 on Sunday, scan approved Monday → 15 back.
  assert.equal(chargeScanFields({ ...base, paidAt: "2026-12-06T20:00:00Z", scanSettledAt: "2026-12-07T10:00:00Z" }).refundDueMinor, 1500);
  // Paid after the credit was on the fee → paid 21, nothing back.
  assert.equal(chargeScanFields({ ...base, paidAt: "2026-12-08T10:00:00Z", scanSettledAt: "2026-12-07T10:00:00Z" }).refundDueMinor, 0);
  assert.equal(chargeScanFields({ ...base, paidAt: "2026-12-06T20:00:00Z", scanSettledAt: "2026-12-07T10:00:00Z", scanRefundedAt: "2026-12-09" }).refundDueMinor, 0);
  assert.equal(chargeScanFields({ ...base, scanCreditMinor: 9999, paidAt: null, scanSettledAt: null }).payableMinor, 0);
});

test("generate invoice: scans then replacement credit; drafts are hidden with no credit", async () => {
  const { GENERATE_INVOICE_SQL } = await import("../src/lib/season-billing-sql");
  const db = await fixture();
  try {
    await db.exec(`
      ALTER TABLE season_invoices ADD COLUMN playing_days integer, ADD COLUMN day_rate_minor integer,
        ADD COLUMN split_between integer;
      ALTER TABLE season_invoices ADD CONSTRAINT one_per_month UNIQUE (season_id, player_id, period);
      ALTER TABLE season_invoices ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor) VALUES (1, 11, 1, 'approved', 1500);
      INSERT INTO season_credits(season_id, player_id, source, guest_charge_id, credit_minor) VALUES (1, 1, 'replacement', 2, 3600);
    `);
    const gen = (period: string, draft: boolean) =>
      db.query(GENERATE_INVOICE_SQL, [1, 1, period, 4, 50000, 14, 14286, `${period}-03`, 14300, draft]);

    // Draft: hidden, no credit, credits stay for publishing.
    assert.equal((await gen("2027-01", true)).rows.length, 1);
    const draft = (await db.query<{ credit_minor: number; is_draft: boolean; hidden: boolean }>(
      `SELECT credit_minor, is_draft, hidden_at IS NOT NULL AS hidden FROM season_invoices WHERE period = '2027-01'`)).rows[0];
    assert.deepEqual(draft, { credit_minor: 0, is_draft: true, hidden: true });
    assert.equal((await db.query(`SELECT 1 FROM season_credits WHERE applied_invoice_id IS NOT NULL`)).rows.length, 0);

    // Normal: scan (15) + replacement credit (36) applied.
    await gen("2027-02", false);
    const live = (await db.query<{ credit_minor: number }>(
      `SELECT credit_minor FROM season_invoices WHERE period = '2027-02'`)).rows[0];
    assert.equal(live.credit_minor, 5100);
    // Re-running skips the existing invoice.
    assert.equal((await gen("2027-02", false)).rows.length, 0);

    // The ledger shows the live invoice but not the draft.
    const due = (await db.query<{ due_key: string; amount_minor: number }>(
      `SELECT due_key, amount_minor FROM dues WHERE source = 'season_invoice'`)).rows;
    assert.equal(due.length, 1);
    assert.equal(due[0].amount_minor, 14300 - 5100);
  } finally {
    await db.close();
  }
});
