CREATE FUNCTION sideline_public_signup_open(p_match integer) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN o.id IS NULL THEN COALESCE(m.availability_open, 1) = 1
    ELSE o.state = 'scheduled' AND s.status = 'active' AND s.subscription_enabled
      AND s.visible_to_players AND COALESCE(m.matchday_status, 'draft') <> 'closed'
      AND CASE WHEN m.availability_override = 'closed' THEN false
               WHEN m.availability_override = 'open' THEN true
               ELSE a.enabled AND NOT a.paused AND now() >= m.signup_opens_at END
    END
  FROM matches m
  LEFT JOIN season_match_occurrences o ON o.match_id = m.id
  LEFT JOIN season_match_automation a ON a.season_id = o.season_id
  LEFT JOIN seasons s ON s.id = o.season_id
  WHERE m.id = p_match
$$;

