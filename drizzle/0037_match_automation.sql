CREATE FUNCTION sideline_confirm_extension(p_match integer, p_extended boolean)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE threshold integer; m matches%ROWTYPE;
BEGIN
  SELECT * INTO m FROM matches WHERE id=p_match FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Match not found.'; END IF;
  IF p_extended AND m.extension_minutes=0 THEN RAISE EXCEPTION 'This booking has no optional extension.'; END IF;
  threshold := m.extension_threshold;
  IF threshold IS NOT NULL AND p_extended AND NOT m.extended
     AND sideline_squad_count(p_match) < threshold THEN
    RAISE EXCEPTION 'Confirm at least % participants before purchasing the extension.', threshold;
  END IF;
  UPDATE matches SET extended=p_extended WHERE id=p_match;
  INSERT INTO match_automation_audit(season_id,match_id,event,actor)
    SELECT season_id,p_match,CASE WHEN p_extended THEN 'Extension confirmed' ELSE 'Extension removed explicitly' END,'admin'
    FROM season_match_occurrences WHERE match_id=p_match;
END
$$;
