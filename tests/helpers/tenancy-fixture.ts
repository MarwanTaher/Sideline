export async function applyMigration(db: PGlite, file: string) {
  const sql = readFileSync(new URL(`../../drizzle/${file}`, import.meta.url), "utf8");
  for (const statement of sql.split("--> statement-breakpoint")) {
    if (statement.trim()) await db.query(statement);
  }
}

/** Every composite (group_id, …) foreign key on a table, as "column -> parent (ON DELETE)". */
export async function groupForeignKeys(db: PGlite, table: string) {
  const rows = (await db.query<{ conname: string; def: string; convalidated: boolean }>(
    `SELECT conname, pg_get_constraintdef(oid) AS def, convalidated
       FROM pg_constraint
      WHERE conrelid = $1::regclass AND contype = 'f' AND conname LIKE '%\\_group\\_fkey'
      ORDER BY conname`, [table])).rows;
  return rows;
}
