CREATE FUNCTION sideline_generate_match(p_season integer, p_link integer DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE a season_match_automation%ROWTYPE; s seasons%ROWTYPE; d date; start_at timestamptz;
  open_at timestamptz; mid integer; existing_id integer; previous_date date;
BEGIN
  SELECT * INTO a FROM season_match_automation WHERE season_id = p_season FOR UPDATE;
  IF NOT FOUND OR NOT a.enabled OR a.paused OR NOT a.needs_generation THEN RETURN NULL; END IF;
  SELECT * INTO s FROM seasons WHERE id = p_season;
  IF s.status <> 'active' OR NOT s.subscription_enabled OR NOT s.visible_to_players
     OR s.end_date IS NULL OR s.rates_confirmed_at IS NULL OR s.terms_final_at IS NULL
     OR s.test_invoice_completed_at IS NULL OR s.reminder_text_reviewed_at IS NULL
     OR length(btrim(s.payment_name)) = 0 OR length(btrim(s.payment_account)) = 0
     OR length(btrim(s.terms)) = 0 OR s.day_rate_minor <= 0 THEN
    RAISE EXCEPTION 'Complete the existing season go-live checklist before enabling automation.';
  END IF;
  IF EXISTS (SELECT 1 FROM season_match_occurrences o JOIN matches m ON m.id = o.match_id
             WHERE o.season_id = p_season AND o.state = 'scheduled' AND m.matchday_status <> 'closed') THEN
    UPDATE season_match_automation SET needs_generation = false,
      last_error=CASE WHEN last_error LIKE 'Match created inside the 24-hour lock.%' THEN last_error ELSE NULL END WHERE season_id = p_season;
    RETURN NULL;
  END IF;
  SELECT MAX(local_date) INTO previous_date FROM season_match_occurrences
    WHERE season_id = p_season AND match_id IS NOT NULL;
  SELECT days INTO d FROM (
    SELECT value::date AS days FROM jsonb_array_elements_text(a.scheduled_dates)
    UNION ALL
    SELECT generated::date FROM generate_series(s.start_date::date::timestamp,s.end_date::date::timestamp,interval '1 day') generated
    WHERE a.scheduled_dates IS NULL AND extract(dow FROM generated)=a.weekday
  ) calendar
  WHERE days BETWEEN s.start_date::date AND s.end_date::date
    AND (days + a.kickoff_time::time) AT TIME ZONE 'Europe/Warsaw' > now()
    AND (previous_date IS NULL OR days > previous_date)
    AND NOT EXISTS (SELECT 1 FROM season_match_occurrences WHERE season_id = p_season AND local_date = days)
  ORDER BY days LIMIT 1;
  IF d IS NULL THEN
    UPDATE season_match_automation SET needs_generation = false,last_error=NULL WHERE season_id=p_season;
    RETURN NULL;
  END IF;
  start_at := (d + a.kickoff_time::time) AT TIME ZONE 'Europe/Warsaw';
  open_at := ((d - ((a.weekday - a.opening_weekday + 7) % 7)) + a.opening_time::time) AT TIME ZONE 'Europe/Warsaw';
  IF open_at >= start_at - interval '24 hours' THEN RAISE EXCEPTION 'Signup must open before the 24-hour change lock.'; END IF;
  SELECT id INTO existing_id FROM matches WHERE season_id = p_season AND played_on = d::text ORDER BY id LIMIT 1;
  IF p_link IS NOT NULL THEN
    IF existing_id IS DISTINCT FROM p_link THEN RAISE EXCEPTION 'Link the existing match on the next scheduled date.'; END IF;
    IF (SELECT COUNT(*) FROM matches WHERE season_id = p_season AND played_on = d::text) <> 1 THEN
      RAISE EXCEPTION 'Resolve duplicate matches before linking.'; END IF;
    mid := p_link;
    IF EXISTS (SELECT 1 FROM matches WHERE id = mid AND (matchday_status <> 'draft' OR kickoff_at <> start_at)) THEN
      RAISE EXCEPTION 'Only a draft match with the scheduled kickoff can be linked.'; END IF;
  ELSIF existing_id IS NOT NULL THEN
    RAISE EXCEPTION 'Existing match % needs explicit linking.', existing_id;
  ELSE
    INSERT INTO matches(played_on, match_time, kickoff_at, num_teams, team_size, total_payment,
      stats_scoring_enabled, status, matchday_status, season_id, location_name, location_lat, location_lng, venue, payment_currency, max_players)
    VALUES (d::text, to_char(a.kickoff_time::time, 'HH12:MI am'), start_at, a.num_teams, 0, 0,
      a.stats_scoring_enabled::integer, 'open', 'draft', p_season, a.location_name, a.location_lat, a.location_lng, a.venue, 'PLN', a.max_players)
    RETURNING id INTO mid;
  END IF;
  INSERT INTO season_match_occurrences(season_id, local_date, match_id, revision, kickoff_at, opens_at, base_cost_minor)
    VALUES (p_season, d, mid, a.revision, start_at, open_at, s.day_rate_minor);
  UPDATE matches SET signup_opens_at = open_at, availability_override = NULL,
    base_minutes = a.base_minutes, extension_minutes = a.extension_minutes,
    extension_threshold=a.extension_threshold, max_players = a.max_players WHERE id = mid;
  INSERT INTO match_availability(match_id, player_id, status, updated_at)
  SELECT mid, ss.player_id, 'in', now() FROM season_subscriptions ss JOIN players p ON p.id = ss.player_id
  WHERE ss.season_id = p_season AND ss.status = 'active' AND p.active = 1 AND p.deleted_at IS NULL
    AND NOT EXISTS(SELECT 1 FROM match_availability WHERE match_id=mid AND player_id=ss.player_id)
  ON CONFLICT (match_id, player_id) DO NOTHING;
  UPDATE season_match_automation SET needs_generation = false,
    last_error=CASE WHEN start_at <= now()+interval '24 hours'
      THEN 'Match created inside the 24-hour lock. Attendance requires explicit admin review.' ELSE NULL END
    WHERE season_id = p_season;
  INSERT INTO match_automation_audit(season_id, match_id, event, actor) VALUES (p_season, mid, 'Match created or linked', 'system');
  RETURN mid;
END
$$;

