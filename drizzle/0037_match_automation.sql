CREATE FUNCTION sideline_waitlist_edit(p_match integer, p_player integer, p_operation text)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE pos bigint; neighbour integer; neighbour_pos bigint;
BEGIN
  PERFORM 1 FROM matches WHERE id = p_match FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Match not found.'; END IF;
  IF p_operation = 'join' THEN
    INSERT INTO match_waitlist(match_id, player_id, position)
    SELECT p_match, p_player, COALESCE(MAX(position), 0) + 1 FROM match_waitlist WHERE match_id = p_match
    ON CONFLICT DO NOTHING;
  ELSIF p_operation = 'leave' THEN
    DELETE FROM match_waitlist WHERE match_id = p_match AND player_id = p_player;
  ELSIF p_operation IN ('up', 'down') THEN
    SELECT position INTO pos FROM match_waitlist WHERE match_id = p_match AND player_id = p_player;
    SELECT player_id, position INTO neighbour, neighbour_pos FROM match_waitlist
    WHERE match_id = p_match AND
      CASE WHEN p_operation = 'up' THEN position < pos ELSE position > pos END
    ORDER BY CASE WHEN p_operation = 'up' THEN -position ELSE position END, player_id LIMIT 1;
    IF neighbour IS NOT NULL THEN
      UPDATE match_waitlist SET position = CASE WHEN player_id = p_player THEN neighbour_pos ELSE pos END
      WHERE match_id = p_match AND player_id IN (p_player, neighbour);
    END IF;
  ELSE RAISE EXCEPTION 'Invalid waitlist operation.'; END IF;
  RETURN (SELECT spot::integer FROM (
    SELECT player_id, row_number() OVER (ORDER BY position, player_id) spot
    FROM match_waitlist WHERE match_id = p_match) ranked WHERE player_id = p_player);
END
$$;

