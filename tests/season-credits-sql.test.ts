test("replacement credit: only for paid replacements on or after the cutover, once", async () => {
  const db = await fixture();
  try {
    const create = async (id: number) => (await db.query(CREATE_REPLACEMENT_CREDIT_SQL, [id])).rows.length;
    assert.equal(await create(1), 0); // old rules: paid directly
    assert.equal(await create(2), 1);
    assert.equal(await create(2), 0); // idempotent
    assert.equal(await create(3), 0); // not paid yet
    assert.equal(await create(4), 0); // extra
    const credits = (await db.query<{ player_id: number; credit_minor: number; match_id: number }>(
      `SELECT player_id, credit_minor, match_id FROM season_credits`)).rows;
    assert.deepEqual(credits, [{ player_id: 1, credit_minor: 3600, match_id: 11 }]);
  } finally {
    await db.close();
  }
});

