CREATE TABLE IF NOT EXISTS match_guests (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
        host_player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        name text NOT NULL,
        position text DEFAULT 'MID' NOT NULL,
        skill integer DEFAULT 40 NOT NULL,
        team_no integer,
        paid integer DEFAULT 0 NOT NULL,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_match_guests_match_id ON match_guests (match_id);
CREATE INDEX IF NOT EXISTS idx_match_guests_host ON match_guests (host_player_id);
