-- Celebration / personality "moments" shown to a player the next time they
-- open the app (MOTM, rank up, hat-trick, badges, team reveal, bummers...).
--
-- One row per (player, kind, match) so generators can be re-run safely.
-- match_id 0 is used for moments not tied to a match.
--
-- Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS player_moments (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id   integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  kind        text    NOT NULL,
  match_id    integer NOT NULL DEFAULT 0,
  payload     jsonb   NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  seen_at     timestamptz,
  CONSTRAINT player_moments_unique UNIQUE (player_id, kind, match_id)
);

CREATE INDEX IF NOT EXISTS idx_player_moments_unseen
  ON player_moments (player_id) WHERE seen_at IS NULL;
