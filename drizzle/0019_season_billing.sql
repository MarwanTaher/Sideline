ALTER TABLE seasons ADD COLUMN IF NOT EXISTS multisport_credit_minor integer DEFAULT 1500 NOT NULL;

--> statement-breakpoint

-- Day of the month the subscription falls due (the 3rd, per the contract).
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS payment_due_day integer DEFAULT 3 NOT NULL;

--> statement-breakpoint

CREATE TABLE IF NOT EXISTS season_invoices (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    season_id integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
    player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    -- 'YYYY-MM'
    period text NOT NULL,
    -- Scheduled playing days in the period; editable when a week is cancelled.
    playing_days integer NOT NULL,
    -- Snapshot of the rate and split at generation time, so a later change to
    -- the season settings never rewrites history.
    day_rate_minor integer NOT NULL,
    split_between integer NOT NULL,
    gross_minor integer NOT NULL,
    credit_minor integer DEFAULT 0 NOT NULL,
    due_date text NOT NULL,
    paid_at timestamptz,
    note text DEFAULT '' NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT season_invoices_unique UNIQUE (season_id, player_id, period)
);

--> statement-breakpoint

CREATE INDEX IF NOT EXISTS season_invoices_period_idx
    ON season_invoices (season_id, period);

--> statement-breakpoint

CREATE TABLE IF NOT EXISTS multisport_scans (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    status text DEFAULT 'pending' NOT NULL,
    credit_minor integer NOT NULL,
    reported_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reviewed_at timestamptz,
    reviewed_by text DEFAULT '' NOT NULL,
    -- Set once the credit lands on a bill, so it can never be counted twice.
    applied_invoice_id integer REFERENCES season_invoices(id) ON DELETE SET NULL,
    CONSTRAINT multisport_scans_status_check
        CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT multisport_scans_unique UNIQUE (match_id, player_id)
);

--> statement-breakpoint

CREATE INDEX IF NOT EXISTS multisport_scans_pending_idx
    ON multisport_scans (status, player_id);
