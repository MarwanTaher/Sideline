-- New features: seasons, achievements, MOTM voting, match reactions, pay link.
-- All statements are idempotent so this file is safe to re-run.

-- Seasons -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS seasons (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        name text NOT NULL,
        start_date text NOT NULL,
        end_date text,
        status text DEFAULT 'active' NOT NULL,
        reset_mode text DEFAULT 'soft' NOT NULL,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT seasons_status_check CHECK (status IN ('active', 'archived')),
        CONSTRAINT seasons_reset_mode_check CHECK (reset_mode IN ('soft', 'hard'))
);

ALTER TABLE matches ADD COLUMN IF NOT EXISTS season_id integer
        REFERENCES seasons(id) ON DELETE SET NULL;

-- Payment link (a pay-by-link URL players can tap; no funds held in-app) -----
ALTER TABLE matches ADD COLUMN IF NOT EXISTS pay_link text DEFAULT '' NOT NULL;

-- Achievements / badges -----------------------------------------------------
CREATE TABLE IF NOT EXISTS player_achievements (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        achievement_key text NOT NULL,
        match_id integer REFERENCES matches(id) ON DELETE SET NULL,
        season_id integer REFERENCES seasons(id) ON DELETE SET NULL,
        detail text DEFAULT '' NOT NULL,
        awarded_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT player_achievements_player_key_unique UNIQUE (player_id, achievement_key)
);
CREATE INDEX IF NOT EXISTS idx_player_achievements_player
        ON player_achievements (player_id);

-- Man of the Match voting ---------------------------------------------------
CREATE TABLE IF NOT EXISTS match_motm_votes (
        match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
        voter_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        voted_for_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT match_motm_votes_pkey PRIMARY KEY (match_id, voter_id)
);
CREATE INDEX IF NOT EXISTS idx_match_motm_votes_match
        ON match_motm_votes (match_id);

-- Match reactions (bounded, ephemeral social; comments stay on WhatsApp) -----
CREATE TABLE IF NOT EXISTS match_reactions (
        match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
        player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        emoji text NOT NULL,
        created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT match_reactions_pkey PRIMARY KEY (match_id, player_id, emoji)
);
CREATE INDEX IF NOT EXISTS idx_match_reactions_match
        ON match_reactions (match_id);
