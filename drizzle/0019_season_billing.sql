-- Season billing: monthly subscription invoices + MultiSport credits.
--
-- Deliberately separate from the per-match `payments` table. Core subscribers
-- owe a monthly amount whether they play or not; everyone else keeps paying per
-- appearance. Mixing the two would make "did you pay?" ambiguous.
--
-- Money is stored in minor units (grosz) so 2,000 / 14 never drifts through a
-- float.
--
-- Idempotent: safe to re-run.

ALTER TABLE seasons ADD COLUMN IF NOT EXISTS day_rate_minor integer DEFAULT 50000 NOT NULL;

