CREATE FUNCTION sideline_seed_subscribers(p_match integer, p_player integer DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE m matches%ROWTYPE; pid integer; added integer := 0;
BEGIN
  SELECT * INTO m FROM matches WHERE id=p_match FOR UPDATE;
  IF NOT FOUND OR m.matchday_status='closed' OR now() >= m.kickoff_at - interval '24 hours' THEN RETURN 0; END IF;
  FOR pid IN SELECT ss.player_id FROM season_subscriptions ss
    JOIN seasons s ON s.id=ss.season_id AND s.subscription_enabled
    JOIN players p ON p.id=ss.player_id AND p.active=1 AND p.deleted_at IS NULL
    WHERE ss.season_id=m.season_id AND ss.status='active' AND (p_player IS NULL OR ss.player_id=p_player)
      AND NOT EXISTS(SELECT 1 FROM match_availability WHERE match_id=p_match AND player_id=ss.player_id)
    ORDER BY ss.accepted_at,ss.player_id
  LOOP
    EXIT WHEN sideline_squad_count(p_match) >= COALESCE(m.max_players,18);
    INSERT INTO match_availability(match_id,player_id,status,updated_at) VALUES(p_match,pid,'in',now()) ON CONFLICT DO NOTHING;
    added := added + 1;
  END LOOP;
  RETURN added;
END
$$;

