CREATE FUNCTION sideline_assert_response(p_match integer, p_player integer, p_public_only boolean DEFAULT false)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE m matches%ROWTYPE; o season_match_occurrences%ROWTYPE; a season_match_automation%ROWTYPE;
BEGIN
  SELECT * INTO m FROM matches WHERE id = p_match FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Match not found.'; END IF;
  IF m.matchday_status = 'closed' THEN RAISE EXCEPTION 'This matchday is closed.'; END IF;
  IF EXISTS (SELECT 1 FROM app_settings WHERE key = 'availability_lock_24h' AND value = '1')
     AND now() >= m.kickoff_at - interval '24 hours' THEN
    RAISE EXCEPTION 'Availability is locked within 24 hours of kickoff. Contact an admin.';
  END IF;
  SELECT * INTO o FROM season_match_occurrences WHERE match_id = p_match;
  IF FOUND THEN
    SELECT * INTO a FROM season_match_automation WHERE season_id = o.season_id;
    -- Automated bookings retain the required lock even if a global default changes.
    IF now() >= m.kickoff_at - interval '24 hours' THEN
      RAISE EXCEPTION 'Availability is locked within 24 hours of kickoff. Contact an admin.';
    END IF;
    IF NOT sideline_public_signup_open(p_match) THEN
      IF p_public_only OR o.state <> 'scheduled' OR NOT a.enabled OR a.paused
         OR m.availability_override = 'closed'
         OR NOT EXISTS (SELECT 1 FROM seasons s WHERE s.id = o.season_id
                         AND s.status = 'active' AND s.subscription_enabled AND s.visible_to_players)
         OR NOT EXISTS (SELECT 1 FROM season_subscriptions ss WHERE ss.season_id = o.season_id
                         AND ss.player_id = p_player AND ss.status = 'active') THEN
        RAISE EXCEPTION 'Public signup is not open for this match.';
      END IF;
    END IF;
  ELSIF NOT sideline_public_signup_open(p_match) THEN
    RAISE EXCEPTION 'Availability is closed for this match.';
  END IF;
END
$$;

