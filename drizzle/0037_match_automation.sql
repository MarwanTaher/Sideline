CREATE FUNCTION sideline_match_edit_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o season_match_occurrences%ROWTYPE; a season_match_automation%ROWTYPE; s seasons%ROWTYPE; opening timestamptz;
BEGIN
  SELECT * INTO o FROM season_match_occurrences WHERE match_id=OLD.id;
  IF NOT FOUND THEN RETURN NEW; END IF;
  IF NEW.season_id IS DISTINCT FROM o.season_id THEN RAISE EXCEPTION 'An automated match cannot be detached from its season.'; END IF;
  IF NEW.played_on IS NOT DISTINCT FROM OLD.played_on AND NEW.kickoff_at IS NOT DISTINCT FROM OLD.kickoff_at THEN RETURN NEW; END IF;
  IF o.state<>'scheduled' OR OLD.matchday_status<>'draft' OR OLD.status<>'open'
     OR now() >= OLD.kickoff_at-interval '24 hours' THEN
    RAISE EXCEPTION 'Only an unlocked draft booking can be rescheduled.';
  END IF;
  SELECT * INTO a FROM season_match_automation WHERE season_id=o.season_id;
  SELECT * INTO s FROM seasons WHERE id=o.season_id;
  IF NEW.played_on::date NOT BETWEEN s.start_date::date AND s.end_date::date
     OR extract(dow FROM NEW.played_on::date)<>a.weekday THEN RAISE EXCEPTION 'Choose a recurring match date inside the season.'; END IF;
  IF NEW.kickoff_at IS NULL OR now() >= NEW.kickoff_at-interval '24 hours' THEN
    RAISE EXCEPTION 'Rescheduling cannot open signup inside the 24-hour lock.';
  END IF;
  opening:=((NEW.played_on::date-((a.weekday-a.opening_weekday+7)%7))+a.opening_time::time) AT TIME ZONE 'Europe/Warsaw';
  IF opening >= NEW.kickoff_at-interval '24 hours' THEN RAISE EXCEPTION 'Signup must open before the 24-hour change lock.'; END IF;
  NEW.signup_opens_at:=opening;
  UPDATE season_match_occurrences SET local_date=NEW.played_on::date,kickoff_at=NEW.kickoff_at,opens_at=opening WHERE id=o.id;
  INSERT INTO match_automation_audit(season_id,match_id,event,actor) VALUES(o.season_id,OLD.id,'Booking rescheduled explicitly','admin');
  RETURN NEW;
END
$$;
