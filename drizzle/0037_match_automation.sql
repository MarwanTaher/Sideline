CREATE FUNCTION sideline_respond(p_match integer, p_player integer, p_status text, p_waitlist boolean)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE cap integer; spot integer;
BEGIN
  PERFORM sideline_assert_response(p_match, p_player);
  IF NOT EXISTS (SELECT 1 FROM players WHERE id = p_player AND active = 1 AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Player is not active.';
  END IF;
  IF p_status NOT IN ('in', 'out') THEN RAISE EXCEPTION 'Invalid availability.'; END IF;
  SELECT COALESCE(max_players, 18) INTO cap FROM matches WHERE id = p_match;
  IF p_status = 'in'
     AND NOT EXISTS (SELECT 1 FROM match_availability WHERE match_id = p_match AND player_id = p_player AND status = 'in')
     AND sideline_squad_count(p_match) >= cap THEN
    IF NOT p_waitlist THEN RAISE EXCEPTION 'Match is full. Ask an admin.'; END IF;
    spot := sideline_waitlist_edit(p_match, p_player, 'join');
    RETURN 'waitlist:' || spot;
  END IF;
  INSERT INTO match_availability(match_id, player_id, status, updated_at)
  VALUES (p_match, p_player, p_status, now())
  ON CONFLICT (match_id, player_id) DO UPDATE SET status = EXCLUDED.status, updated_at = now();
  PERFORM sideline_waitlist_edit(p_match, p_player, 'leave');
  IF p_status = 'out' THEN DELETE FROM match_guests WHERE match_id = p_match AND host_player_id = p_player; END IF;
  RETURN p_status;
END
$$;

