-- P2.1: credit for a subscriber whose offered seat was taken by a replacement
-- who paid the group. Consumed by the invoice allocator after MultiSport
-- scans, with the same applied/settled lifecycle as a scan.
CREATE TABLE IF NOT EXISTS season_credits (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	season_id integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
	player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
	source text NOT NULL DEFAULT 'replacement',
	guest_charge_id integer REFERENCES guest_charges(id) ON DELETE SET NULL,
	match_id integer REFERENCES matches(id) ON DELETE SET NULL,
	credit_minor integer NOT NULL CHECK (credit_minor > 0),
	applied_invoice_id integer REFERENCES season_invoices(id) ON DELETE SET NULL,
	settled_at timestamptz,
	settled_as text,
	created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT season_credits_source_check CHECK (source IN ('replacement')),
	CONSTRAINT season_credits_settled_check CHECK (
		(settled_at IS NULL AND settled_as IS NULL)
		OR (settled_at IS NOT NULL AND settled_as IN ('refunded', 'fund')
		    AND applied_invoice_id IS NULL)
	)
);

