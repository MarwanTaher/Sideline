-- Predictions mini-game: one "who wins the matchday" pick per player per match.
-- Picks open once teams are published and lock at kickoff (enforced in the app).
CREATE TABLE IF NOT EXISTS predictions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id integer NOT NULL,
    player_id integer NOT NULL,
    team_no integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT predictions_match_id_fkey FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE,
    CONSTRAINT predictions_player_id_fkey FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE,
    CONSTRAINT predictions_match_id_player_id_key UNIQUE (match_id, player_id),
    CONSTRAINT predictions_team_no_check CHECK (team_no > 0)
);

