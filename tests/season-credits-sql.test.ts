import assert from "node:assert/strict";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { CREATE_REPLACEMENT_CREDIT_SQL, PLAYER_CHARGES_SQL } from "../src/lib/season-fund-sql";
import { REALLOCATE_CREDIT_SQL } from "../src/lib/season-billing-sql";
import { LEFTOVER_CREDITS_SQL, SETTLE_LEFTOVER_CREDIT_SQL } from "../src/lib/multisport-sql";
import { PLAYER_DUES_SQL } from "../src/lib/dues-sql";
import { toDue, type DueRow } from "../src/lib/dues-summary";

// In-memory fixtures only: this suite never loads DATABASE_URL or contacts Neon.
async function fixture(): Promise<PGlite> {
  const db = new PGlite();
  await db.exec(`
    CREATE TABLE players(id integer PRIMARY KEY, name text);
    CREATE TABLE seasons(id integer PRIMARY KEY, subscription_enabled boolean, new_rules_from text);
    CREATE TABLE matches(id integer PRIMARY KEY, season_id integer, played_on text,
      payments_active integer DEFAULT 0, total_payment double precision DEFAULT 0,
      payment_currency text, share_minor integer);
    CREATE TABLE match_players(match_id integer, player_id integer);
    CREATE TABLE payments(match_id integer, player_id integer, paid integer, updated_at timestamp);
    CREATE TABLE match_guests(id integer PRIMARY KEY, match_id integer, name text, host_player_id integer,
      paid integer, status text);
    CREATE TABLE guest_charges(id integer PRIMARY KEY, match_id integer, player_id integer, guest_id integer,
      amount_minor integer, kind text, owed_to_player_id integer, paid_at timestamptz,
      scan_credit_minor integer DEFAULT 0, scan_refunded_at timestamptz);
    CREATE TABLE season_invoices(id integer PRIMARY KEY, season_id integer, player_id integer, period text,
      gross_minor integer, credit_minor integer DEFAULT 0, due_date text,
      paid_at timestamptz, declared_paid_at timestamptz, hidden_at timestamptz);
    CREATE TABLE multisport_scans(id integer PRIMARY KEY, match_id integer, player_id integer, status text,
      credit_minor integer, applied_invoice_id integer, settled_at timestamptz, settled_as text);
    CREATE TABLE season_credits(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      season_id integer, player_id integer, source text, guest_charge_id integer, match_id integer,
      credit_minor integer, applied_invoice_id integer, settled_at timestamptz, settled_as text);
    CREATE UNIQUE INDEX season_credits_charge_idx ON season_credits (guest_charge_id) WHERE guest_charge_id IS NOT NULL;
    CREATE TABLE season_subscriptions(season_id integer, player_id integer, status text);
    CREATE TABLE fund_adjustments(id integer GENERATED BY DEFAULT AS IDENTITY, season_id integer,
      amount_minor integer, note text, created_by text);

    INSERT INTO players VALUES (1, 'Adam'), (2, 'Ben'), (3, 'Cara');
    INSERT INTO seasons VALUES (1, true, '2026-12-01');
    INSERT INTO season_subscriptions VALUES (1, 1, 'active');
    INSERT INTO matches(id, season_id, played_on) VALUES (10, 1, '2026-11-29'), (11, 1, '2026-12-06'), (12, 1, '2026-12-13');
    -- Ben replaces Adam: before the cutover (10) and after it (11, 12).
    INSERT INTO guest_charges(id, match_id, player_id, amount_minor, kind, owed_to_player_id, paid_at) VALUES
      (1, 10, 2, 3600, 'replacement', 1, now()),
      (2, 11, 2, 3600, 'replacement', 1, now()),
      (3, 12, 2, 3600, 'replacement', 1, NULL),
      (4, 11, 3, 3600, 'extra', NULL, now());
  `);
  return db;
}

test("replacement credit: only for paid replacements on or after the cutover, once", async () => {
  const db = await fixture();
  try {
    const create = async (id: number) => (await db.query(CREATE_REPLACEMENT_CREDIT_SQL, [id])).rows.length;
    assert.equal(await create(1), 0); // old rules: paid directly
    assert.equal(await create(2), 1);
    assert.equal(await create(2), 0); // idempotent
    assert.equal(await create(3), 0); // not paid yet
    assert.equal(await create(4), 0); // extra
    const credits = (await db.query<{ player_id: number; credit_minor: number; match_id: number }>(
      `SELECT player_id, credit_minor, match_id FROM season_credits`)).rows;
    assert.deepEqual(credits, [{ player_id: 1, credit_minor: 3600, match_id: 11 }]);
  } finally {
    await db.close();
  }
});

test("replacement charges: new-rules ones pay the group in charges and dues", async () => {
  const db = await fixture();
  try {
    const charges = (await db.query<{ id: number; new_rules: boolean }>(PLAYER_CHARGES_SQL, [2, null, false])).rows;
    assert.deepEqual(charges.map((c) => [Number(c.id), c.new_rules]), [[3, true], [2, true], [1, false]]);

    const dues = (await db.query<DueRow>(PLAYER_DUES_SQL, [2])).rows.map(toDue);
    assert.deepEqual(dues.map((d) => [d.key, d.payee]), [
      ["charge:3", "group"],
      ["charge:2", "group"],
      ["charge:1", "player"],
    ]);
  } finally {
    await db.close();
  }
});

test("invoice credit: scans first, then replacement credits into what is left", async () => {
  const db = await fixture();
  try {
    await db.exec(`
      -- 143 PLN bill; 10 scans x 15 = 150 would overflow, so only 9 fit (135).
      INSERT INTO season_invoices(id, season_id, player_id, period, gross_minor, due_date)
        VALUES (100, 1, 1, '2027-01', 14286, '2027-01-03');
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor)
        SELECT g, 11, 1, 'approved', 1500 FROM generate_series(1, 2) g;
      INSERT INTO season_credits(season_id, player_id, source, guest_charge_id, credit_minor)
        VALUES (1, 1, 'replacement', 2, 3600), (1, 1, 'replacement', NULL, 3600),
               (1, 1, 'replacement', NULL, 9000);
    `);
    const run = async () => {
      for (const statement of REALLOCATE_CREDIT_SQL) await db.query(statement, [100]);
    };
    await run();
    const credit = async () =>
      (await db.query<{ credit_minor: number }>(`SELECT credit_minor FROM season_invoices WHERE id = 100`)).rows[0].credit_minor;
    // 2 scans (30) + 36 + 36 = 102; the 90 credit doesn't fit 143 any more.
    assert.equal(await credit(), 10200);
    const applied = (await db.query<{ id: number }>(
      `SELECT id FROM season_credits WHERE applied_invoice_id = 100 ORDER BY id`)).rows.map((r) => Number(r.id));
    assert.deepEqual(applied, [1, 2]);

    // Re-running is stable.
    await run();
    assert.equal(await credit(), 10200);

    // A smaller bill drops the replacement credits before the scans.
    await db.exec(`UPDATE season_invoices SET gross_minor = 5000 WHERE id = 100`);
    await run();
    assert.equal(await credit(), 3000);

    // Paid bills are never refitted.
    await db.exec(`UPDATE season_invoices SET gross_minor = 14286, paid_at = now() WHERE id = 100`);
    await run();
    assert.equal(await credit(), 3000);
  } finally {
    await db.close();
  }
});

test("leftover credit: scans and replacement credits listed and settled together", async () => {
  const db = await fixture();
  try {
    await db.exec(`
      INSERT INTO multisport_scans(id, match_id, player_id, status, credit_minor) VALUES (1, 11, 1, 'approved', 1500);
      INSERT INTO season_credits(season_id, player_id, source, guest_charge_id, credit_minor)
        VALUES (1, 1, 'replacement', 2, 3600);
    `);
    const left = (await db.query<{ credit: number; scans: number; replacements: number }>(
      LEFTOVER_CREDITS_SQL, [1])).rows;
    assert.deepEqual(left.map((r) => [r.credit, r.scans, r.replacements]), [[5100, 1, 1]]);

    const settled = (await db.query<{ amount: number }>(SETTLE_LEFTOVER_CREDIT_SQL, [1, 1, "fund", "end", "admin"])).rows;
    assert.equal(settled[0].amount, 5100);
    const fund = (await db.query<{ amount_minor: number }>(`SELECT amount_minor FROM fund_adjustments`)).rows;
    assert.deepEqual(fund, [{ amount_minor: 5100 }]);
    assert.equal((await db.query(LEFTOVER_CREDITS_SQL, [1])).rows.length, 0);
  } finally {
    await db.close();
  }
});
