-- M1 of docs/platform/01-M1-TENANCY-FOUNDATION.md: the groups (tenants) table.
--
-- One row per group. Krakow Pyramids, the founding group, is id 1; every
-- existing row will be backfilled to it by 0041-0044. Nothing reads this
-- table yet, so applying it changes no behaviour.
--
-- `timezone`, `currency` and `locale` are stored now but only read from M4;
-- until then the code keeps its Europe/Warsaw / PLN constants.
--
-- Additive and idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS groups (
	id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	slug text NOT NULL,
	name text NOT NULL,
	timezone text NOT NULL DEFAULT 'Europe/Warsaw',
	currency text NOT NULL DEFAULT 'PLN',
	locale text NOT NULL DEFAULT 'en-GB',
	status text NOT NULL DEFAULT 'active',
	created_at timestamptz NOT NULL DEFAULT now(),
	CONSTRAINT groups_slug_key UNIQUE (slug),
	-- 3-40 chars, lowercase letters/digits/hyphens, no leading/trailing hyphen.
	CONSTRAINT groups_slug_format CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'),
	-- Words the platform routes use at the top level or under /g/.
	CONSTRAINT groups_slug_reserved CHECK (slug NOT IN (
		'g', 'api', 'platform', 'account', 'accounts', 'login', 'logout', 'register',
		'reset', 'magic', 'join', 'share', 'admin', 'new', 'groups', 'settings'
	)),
	CONSTRAINT groups_name_not_blank CHECK (btrim(name) <> ''),
	CONSTRAINT groups_currency_format CHECK (currency ~ '^[A-Z]{3}$'),
	CONSTRAINT groups_status_check CHECK (status IN ('active', 'suspended', 'archived'))
);

