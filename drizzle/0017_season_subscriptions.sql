-- Season subscriptions (winter 2026/2027 contract model).
--
-- A subscription season has a fixed roster of core players who are committed
-- for the whole contract period. They are marked IN automatically for every
-- match inside the window; the remaining places fill normally.
--
-- Liability is deliberately NOT modelled here: a subscriber who marks OUT for
-- one Sunday still owes for that day, so availability and billing must stay
-- separate concerns. Billing lands in a later migration.
--
-- Idempotent: safe to re-run.

ALTER TABLE seasons ADD COLUMN IF NOT EXISTS subscription_enabled boolean DEFAULT false NOT NULL;

--> statement-breakpoint

-- Size of the committed core group (14 for winter 2026/2027).
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS subscriber_cap integer DEFAULT 14 NOT NULL;

--> statement-breakpoint

-- Terms players must accept to take one of the core places.
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS terms text DEFAULT '' NOT NULL;

--> statement-breakpoint

-- Bumping this re-prompts everyone to accept the revised terms.
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS terms_version integer DEFAULT 1 NOT NULL;

--> statement-breakpoint

-- Whether sign-up is currently open (closed once the group is settled).
ALTER TABLE seasons ADD COLUMN IF NOT EXISTS signup_open boolean DEFAULT true NOT NULL;

--> statement-breakpoint

CREATE TABLE IF NOT EXISTS season_subscriptions (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    season_id integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
    player_id integer NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    status text DEFAULT 'active' NOT NULL,
    -- Which version of the terms they agreed to, and when.
    accepted_terms_version integer DEFAULT 1 NOT NULL,
    accepted_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    withdrawn_at timestamptz,
    note text DEFAULT '' NOT NULL,
    CONSTRAINT season_subscriptions_status_check
        CHECK (status IN ('active', 'withdrawn')),
    CONSTRAINT season_subscriptions_unique UNIQUE (season_id, player_id)
);

--> statement-breakpoint

-- accepted_at ordering decides who holds a place: first come, first served.
CREATE INDEX IF NOT EXISTS season_subscriptions_season_idx
    ON season_subscriptions (season_id, status, accepted_at);
