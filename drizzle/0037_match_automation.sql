CREATE FUNCTION sideline_capacity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE cap integer; mid integer;
BEGIN
  mid := NEW.match_id;
  SELECT COALESCE(max_players, 18) INTO cap FROM matches WHERE id = mid FOR UPDATE;
  IF TG_TABLE_NAME = 'match_availability' THEN
    IF NEW.status <> 'in' OR (TG_OP = 'UPDATE' AND OLD.status = 'in') THEN RETURN NEW; END IF;
    IF EXISTS(SELECT 1 FROM match_availability WHERE match_id=mid AND player_id=NEW.player_id AND status='in') THEN RETURN NEW; END IF;
  ELSE
    IF NEW.status <> 'approved' OR (TG_OP = 'UPDATE' AND OLD.status = 'approved') THEN RETURN NEW; END IF;
  END IF;
  IF EXISTS (SELECT 1 FROM season_match_occurrences WHERE match_id = mid)
     AND sideline_squad_count(mid) >= cap THEN RAISE EXCEPTION 'Match is full. Increase capacity before adding a participant.'; END IF;
  RETURN NEW;
END
$$;

